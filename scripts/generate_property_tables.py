#!/usr/bin/env python3
"""Generate bit-exact Rust constants from recovered initializer evidence."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def main():
    document=json.loads((ROOT/'analysis/property_tables.json').read_text())
    lines=['//! Binary32 values recovered from the PCTran.exe initializer.', '// Generated by scripts/generate_property_tables.py; do not hand-edit.']
    for name,key in [('SATURATION_TEMPERATURE','saturation_temperature'),('SATURATION_PRESSURE','saturation_pressure_44'),('VAPOR_PRESSURE','saturation_pressure_68'),('VAPOR_SPECIFIC_VOLUME','saturated_vapor_specific_volume'),('DISCHARGE_PRESSURE','auxiliary_grid'),('LIQUID_DISCHARGE_FLUX','auxiliary_curve_1'),('VAPOR_DISCHARGE_FLUX','auxiliary_curve_2')]:
        array=next(a for a in document['arrays'] if a['name']==key)
        lines.append(f'pub const {name}: [f32; {len(array["values"])}] = [')
        lines.extend(f'    f32::from_bits(0x{entry["bits"]}), // index {entry["index"]}, store {entry["store_va"]:#x}' for entry in array['evidence'])
        lines.append('];')
    (ROOT/'rusttran/src/property_tables.rs').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':main()
