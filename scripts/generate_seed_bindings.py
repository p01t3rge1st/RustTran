#!/usr/bin/env python3
"""Generate reviewed static Rust binding operands from preserved native evidence."""
import json,struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
import re
schema=(ROOT/'analysis/data/ListData/schema.sql').read_text().split('CREATE TABLE IF NOT EXISTS "icthermodata"',1)[1].split(');',1)[0]
types=dict(re.findall(r'"([^"\n]+)"\s+(DOUBLE PRECISION|REAL|INTEGER)',schema))
source=json.loads((ROOT/'analysis/rea/seed-bindings.json').read_text())
lines=['// Generated by scripts/generate_seed_bindings.py; source: analysis/rea/seed-bindings.json.','// Original binary SHA-256: '+source['original_sha256'], 'pub const IC_BINDINGS: &[FieldBinding] = &[']
for item in source['bindings']:
    bits=lambda v:struct.unpack('<I',struct.pack('<f',v))[0]
    lines.append(f'    FieldBinding {{ field: {json.dumps(item["field"])}, address: {int(item["target"],16):#x}, factor: f32::from_bits({bits(item["factor"]):#010x}), offset: f32::from_bits({bits(item["offset"]):#010x}), divide: {str(item['mode']=='divide').lower()}, source_single: {str(types[item['field'].lower()]=='REAL').lower()} }},')
lines.append('];')
lines.append('pub const IC_INTEGER_BINDINGS: &[IntegerBinding] = &[')
for item in source.get('integer_bindings',[]):
    lines.append(f'    IntegerBinding {{ field: {json.dumps(item["field"])}, address: {int(item["target"],16):#x}, bits: {item["bits"]} }},')
lines.append('];');(ROOT/'rusttran/src/seed_bindings.rs').write_text('\n'.join(lines)+'\n')

model=json.loads((ROOT/'analysis/rea/model-bindings.json').read_text())
lines=['// Generated from original model read blocks and native runtime operation traces.','pub const MODEL_BINDINGS: &[ModelFieldBinding] = &[']
for item in model['bindings']:
    operations=[]
    for op in item['operations']:
        bits=struct.unpack('<Q',struct.pack('<d',op['constant']))[0]
        kind={'__vbaVarMul':'Multiply','__vbaVarDiv':'Divide','__vbaVarAdd':'Add'}[op['operator']]
        operations.append(f'NumberOp {{ kind: NumberOpKind::{kind}, constant: f64::from_bits({bits:#018x}), constant_left: {str(op["constant_left"]).lower()}, single_result: {str(op["result_type"]==4).lower()} }}')
    lines.append(f'    ModelFieldBinding {{ field: {json.dumps(item["field"])}, address: {int(item["target"],16):#x}, source_single: {str(item["source_type"]=="REAL").lower()}, output_bits: {item["output_bits"]}, curve: {json.dumps(item["curve"])}, index: {item["index"]}, operations: &[{", ".join(operations)}] }},')
lines.append('];');(ROOT/'rusttran/src/model_bindings.rs').write_text('\n'.join(lines)+'\n')
